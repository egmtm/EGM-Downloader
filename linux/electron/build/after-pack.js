// linux/electron/build/after-pack.js
//
// Sandbox-fix wrapper for AppImage on Linux.
//
// Why this exists:
//   AppImages mount as a regular user (not root). Chromium's chrome-sandbox
//   helper needs to be SUID root to run, which is impossible inside an
//   AppImage's read-only squashfs mount. On Ubuntu 24.04+, this is made
//   worse by kernel.apparmor_restrict_unprivileged_userns=1 being default,
//   which blocks the namespace-sandbox fallback too.
//
//   The result on first launch is:
//     [FATAL:setuid_sandbox_host.cc(158)] The SUID sandbox helper binary
//     was found, but is not configured correctly.
//
// Why app.commandLine.appendSwitch('no-sandbox') in main.js does NOT fix it:
//   That call runs inside the Electron main process. The SUID check happens
//   at Chromium init, BEFORE main.js is loaded. The flag must be passed as
//   a process argument to the binary itself.
//
// What this hook does:
//   1. Renames the bundled executable from 'egm-downloader' to
//      'egm-downloader-bin'.
//   2. Drops a tiny POSIX-shell wrapper at 'egm-downloader' that exec's
//      the real binary with --no-sandbox prepended to argv.
//
//   The AppImage's AppRun calls `egm-downloader`, which is now our wrapper,
//   so --no-sandbox is always passed. The user sees no change in behaviour.
//
// This is the same approach used by VS Code, Discord, Slack, and most
// production Electron AppImages.

const fs   = require('fs');
const path = require('path');

exports.default = async function afterPack(context) {
  if (context.electronPlatformName !== 'linux') return;

  const appOutDir      = context.appOutDir;
  const executableName = context.packager.executableName || 'egm-downloader';
  const wrapperPath    = path.join(appOutDir, executableName);
  const realBinPath    = path.join(appOutDir, executableName + '-bin');

  if (!fs.existsSync(wrapperPath)) {
    throw new Error(`afterPack: expected executable at ${wrapperPath} but it was not found.`);
  }

  // If a previous build left a -bin behind, drop it before renaming.
  if (fs.existsSync(realBinPath)) fs.unlinkSync(realBinPath);

  fs.renameSync(wrapperPath, realBinPath);

  const wrapper = `#!/bin/sh
# EGM Downloader launch wrapper — adds --no-sandbox so Chromium does not
# abort on the AppImage SUID-sandbox check. Generated by build/after-pack.js.
HERE="$(dirname "$(readlink -f "$0")")"
exec "$HERE/${executableName}-bin" --no-sandbox "$@"
`;
  fs.writeFileSync(wrapperPath, wrapper, { mode: 0o755 });

  console.log(`  • afterPack    sandbox-fix wrapper installed at ${wrapperPath}`);
  console.log(`  • afterPack    real binary moved to ${realBinPath}`);
};
