"""
Write the NSIS include that removes what the installer folder puts in the install root.

The top level files of the Electron runtime change between Electron versions (a DLL added or dropped),
so the list is read from the built folder at build time instead of being kept by hand: one Delete per
top level file and one RMDir /r per top level folder (resources, locales). Removing those folders as a
whole also removes what Python writes into them at runtime (__pycache__ under resources\\python).

usage: uninstall_list.py <installer folder> <output .nsh>
"""
import sys
from pathlib import Path

HEADER = """; Generated by windows/installer/uninstall_list.py from the installer folder. Do not edit.
; Everything the installer folder puts in the install root: the uninstaller removes exactly these.
"""


def entries(folder):
    """(files, folders) at the top of the installer folder, sorted."""
    folder = Path(folder)
    if not (folder / "EGM Downloader.exe").is_file() or not (folder / "resources" / "app.asar").is_file():
        raise SystemExit(f"{folder} is not an installer folder (no EGM Downloader.exe or resources/app.asar)")
    files = sorted(p.name for p in folder.iterdir() if p.is_file())
    dirs = sorted(p.name for p in folder.iterdir() if p.is_dir())
    for name in files + dirs:
        if not name or any(c in name for c in '"$\\/*?'):
            raise SystemExit(f"unexpected name in the installer folder: {name!r}")
    return files, dirs


def render(folder):
    files, dirs = entries(folder)
    lines = [HEADER, "!macro EGM_REMOVE_APP_FOLDER"]
    lines += [f'  Delete "$INSTDIR\\{n}"' for n in files]
    lines += [f'  RMDir /r "$INSTDIR\\{n}"' for n in dirs]
    lines.append("!macroend")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)
    text = render(sys.argv[1])
    Path(sys.argv[2]).write_text(text, encoding="utf-8")
    print(f"   ✓ Uninstall list: {text.count('Delete ')} files, {text.count('RMDir /r')} folders")
